#pragma once

#include "Nametag.h"

namespace zoom::camera
{
    constexpr uintptr_t kCallRva = 0x4E088F2;
    constexpr uintptr_t kTargetRva = 0x6DA5E10;
    constexpr unsigned int kMouseAndKeyboard = 1;
    constexpr unsigned char kCall[] = {0xE8, 0x19, 0xD5, 0xF9, 0x01};

    inline bool Matches(uintptr_t base)
    {
        constexpr unsigned char mode[] = {0x8B, 0x5A, 0x18, 0x83, 0xFB, 0x02, 0x75, 0x5A};
        constexpr unsigned char load[] = {0xF2, 0x44, 0x0F, 0x10, 0x46, 0x34};
        constexpr unsigned char clear[] = {0x48, 0xC7, 0x46, 0x34, 0, 0, 0, 0};
        constexpr unsigned char pack[] = {
            0x44, 0x0F, 0x59, 0x05, 0x48, 0xE0, 0x40, 0x0A, 0x0F, 0x28, 0x0D, 0x51, 0xE0, 0x40, 0x0A,
            0xF3, 0x0F, 0x10, 0xC8, 0x41, 0x0F, 0x59, 0xC8, 0x0F, 0x13, 0x4C, 0x24, 0x28
        };
        constexpr unsigned char caller[] = {
            0x48, 0x8D, 0x54, 0x24, 0x28, 0x48, 0x89, 0xC1, 0xE8, 0x19, 0xD5, 0xF9, 0x01,
            0x0F, 0xB6, 0x86, 0x9C, 0, 0, 0
        };
        constexpr unsigned char target[] = {
            0x56, 0x57, 0x55, 0x53, 0x48, 0x83, 0xEC, 0x68, 0x44, 0x0F, 0x29, 0x44, 0x24, 0x50,
            0x0F, 0x29, 0x7C, 0x24, 0x40, 0x0F, 0x29, 0x74, 0x24, 0x30, 0x48, 0x89, 0xCE,
            0x48, 0x8B, 0x05, 0x8E, 0x52, 0x56, 0x0B, 0x48, 0x31, 0xE0, 0x48, 0x89, 0x44, 0x24,
            0x28, 0x48, 0x8B, 0x1A
        };
        constexpr unsigned char consumer[] = {
            0x45, 0x0F, 0x14, 0xC0, 0x44, 0x0F, 0x59, 0xC7, 0x44, 0x0F, 0x13, 0x44, 0x24, 0x20,
            0x48, 0x8D, 0x54, 0x24, 0x20, 0x48, 0x89, 0xF1, 0xE8, 0x43, 0, 0, 0
        };
        const auto check = [base](uintptr_t rva, const auto& bytes)
        {
            MEMORY_BASIC_INFORMATION memory{};
            const uintptr_t address = base + rva;
            return VirtualQuery(reinterpret_cast<const void*>(address), &memory, sizeof(memory)) != 0 &&
                memory.Type == MEM_IMAGE && memory.AllocationBase == reinterpret_cast<const void*>(base) &&
                memory.Protect == PAGE_EXECUTE_READ && nametag::Matches(address, bytes, sizeof(bytes));
        };
        return base && base <= UINTPTR_MAX - 0x6DA5FF2 - sizeof(consumer) &&
            check(0x4E08523, mode) && check(0x4E085DE, load) && check(0x4E086A3, clear) &&
            check(0x4E08890, pack) && check(kCallRva - 8, caller) && check(kTargetRva, target) &&
            check(0x6DA5FF2, consumer);
    }

    inline auto Relay(uintptr_t callback)
    {
        // The original call supplies RCX and RDX. Pass the caller's input mode
        // in R8D and tail-jump so the original return address stays on the stack.
        std::array<unsigned char, 15> bytes{0x41, 0x89, 0xD8, 0x48, 0xB8, 0, 0, 0, 0, 0, 0, 0, 0, 0xFF, 0xE0};
        std::memcpy(bytes.data() + 5, &callback, sizeof(callback));
        return bytes;
    }
}
